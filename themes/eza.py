def render(p, variant):
    lines = ["# Miami Cruise for eza. Generated by build.py; edit themes/eza.py, not this file.",
             f"# Variant: {variant}. Copy to your eza config directory as theme.yml.",
             "colourful: true", ""]

    def emit(mapping, indent=0):
        for key, value in mapping.items():
            prefix = " " * indent + key + ":"
            if isinstance(value, dict):
                lines.append(prefix)
                emit(value, indent + 2)
            else:
                # Override inherited bold/dim/underline so the exact palette stays readable.
                attrs = [f'foreground: "{p[value]}"', "is_bold: false", "is_dimmed: false",
                         "is_underline: false"]
                lines.append(prefix + " { " + ", ".join(attrs) + " }")

    emit(roles())
    return "\n".join(lines) + "\n"


