"""WezTerm exporter: one Lua module with both palettes, system dark/light follow and an override.

Output: dist/wezterm/miami-cruise.lua  (copy next to wezterm.lua, then `require` it).
WezTerm re-evaluates the config when the system appearance changes, so following the system
needs no event handler. Terminals have no glow, so this is the flat palette.
"""
