def export(pals, dist: Path):
    out = dist / "wezterm"
    out.mkdir(parents=True, exist_ok=True)
    d, l = pals["dark"][0], pals["light"][0]
    body = ",\n".join(
        [_lua_table("dark", d), _lua_table("light", l), _lua_list("dark_ansi", _hl.ansi(d)), _lua_list("light_ansi", _hl.ansi(l))]
    ) + ","
    (out / "miami-cruise.lua").write_text(LUA.replace("@@PALETTES@@", body))
