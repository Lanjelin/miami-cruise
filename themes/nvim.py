def _palette_lua(name, pal):
    rows = ",\n".join(f'    ["{k}"] = "{pal[k]}"' for k in TOKEN_ORDER)
    return f"  {name} = {{\n{rows},\n  }}"


def _lua_spec(spec):
    if "link" in spec:
        return '{ link = "%s" }' % spec["link"]
    parts = [f'{k} = "{spec[k]}"' for k in ("fg", "bg", "sp") if k in spec]
    parts += [f"{k} = true" for k in ("bold", "italic", "underline", "undercurl") if spec.get(k)]
    return "{ " + ", ".join(parts) + " }"


def _core_lua(pals):
    blocks = []
    for name in ("dark", "light"):
        rows = ",\n".join(f"    {g} = {_lua_spec(sp)}" for g, sp in _hl.core(pals[name][0]).items())
        blocks.append(f"  {name} = {{\n{rows},\n  }}")
    return ",\n".join(blocks) + ","


