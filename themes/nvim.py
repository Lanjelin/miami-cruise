def export(pals, dist: Path):
    out = dist / "nvim" / "colors"
    out.mkdir(parents=True, exist_ok=True)
    body = ",\n".join(_palette_lua(n, pals[n][0]) for n in ("dark", "light")) + ","
    lua = LUA.replace("@@PALETTES@@", body).replace("@@CORE@@", _core_lua(pals))
    ansi = ",\n".join(
        "  %s = { %s }" % (name, ", ".join('"%s"' % c for c in _hl.ansi(pals[name][0]))) for name in ("dark", "light")
    ) + ","
    lua = lua.replace("@@ANSI@@", ansi)
    (out / "miami-cruise.lua").write_text(lua)
