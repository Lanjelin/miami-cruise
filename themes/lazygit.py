def export(pals, dist):
    out = dist / "lazygit"
    out.mkdir(parents=True, exist_ok=True)
    (out / "miami-cruise.yml").write_text(render(pals))
    for variant in pals:
        (out / f"miami-cruise-{variant}.yml").write_text(render(pals, variant))
