"""Native lazygit GUI themes; terminal/Git or an optional delta renderer colours diffs."""
import json

from palette import contrast


def theme(p):
    for foreground, background in (("text", "hover"), ("text", "bg"),
                                   ("on-accent", "accent"), ("bg", "warning")):
        if contrast(p[foreground], p[background]) < 4.5:
            raise ValueError(f"lazygit: {foreground} on {background} is below 4.5:1")
    return {
        "activeBorderColor": [p["accent"], "bold"],
        # Lazygit also uses this colour for inactive panel/tab labels.
        "inactiveBorderColor": [p["disabled"]],
        "searchingActiveBorderColor": [p["info"], "bold"],
        "optionsTextColor": [p["info"]],
        "selectedLineFgColor": [p["text"], "bold"],
        "selectedLineBgColor": [p["hover"]],
        "inactiveViewSelectedLineBgColor": [p["bg"]],
        "cherryPickedCommitFgColor": [p["on-accent"]],
        "cherryPickedCommitBgColor": [p["accent"]],
        "markedBaseCommitFgColor": [p["bg"]],
        "markedBaseCommitBgColor": [p["warning"]],
        "unstagedChangesColor": [p["danger"]],
        "defaultFgColor": [p["text"]],
        "authorColors": {"*": p["orchid"]},
    }


def yaml(data, indent=0):
    """Emit this small native YAML subset, quoting hex values and wildcard keys."""
    lines = []
    for key, value in data.items():
        label = json.dumps(key) if key == "*" else key
        prefix = " " * indent + label + ":"
        if isinstance(value, dict):
            lines.append(prefix)
            lines.extend(yaml(value, indent + 2))
        else:
            lines.append(prefix + " " + json.dumps(value))
    return lines


def render(pals, variant=None):
    if variant:
        colours = theme(pals[variant][0])
        # An existing base config's scheme-specific override must not beat this layer.
        gui = dict(colorScheme=variant, theme=colours, **{variant + "Theme": colours})
    else:
        gui = dict(colorScheme="auto", theme=theme(pals["dark"][0]),
                   darkTheme=theme(pals["dark"][0]), lightTheme=theme(pals["light"][0]))
    return ("# Miami Cruise for lazygit. Generated by build.py; edit themes/lazygit.py.\n"
            "# Merge as a separate config layer; this file changes appearance only.\n" +
            "\n".join(yaml({"gui": gui})) + "\n")


