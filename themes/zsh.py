"""Oh My Zsh prompt based on gnzh: keep its segments and geometry, change colours."""
from pathlib import Path

from palette import contrast


def render(p, variant):
    roles = {
        "user": "success", "root": "danger", "local_host": "success",
        "ssh_host": "danger", "at": "info", "path": "info",
        "git": "warning", "ruby": "danger", "venv": "danger",
        "error": "danger", "line": "muted", "arrow": "accent",
    }
    for role, token in roles.items():
        if contrast(p[token], p["bg"]) < 4.5:
            raise ValueError(f"zsh: {role} on bg is below 4.5:1")
    c = {role: p[token] for role, token in roles.items()}
    licence = (Path(__file__).parent / "zsh-LICENSE.txt").read_text()
    notice = "\n".join("# " + line if line else "#" for line in licence.splitlines())
    return f'''# Miami Cruise {variant} for Oh My Zsh. Generated by build.py.
# Prompt layout adapted from Oh My Zsh's gnzh theme (MIT; see LICENSE-oh-my-zsh.txt).
# Only prompt colours change. Keep your existing plugins and shell configuration.
{notice}
setopt prompt_subst

() {{
  local PR_USER PR_USER_OP PR_PROMPT PR_HOST

  if [[ $UID -ne 0 ]]; then
    PR_USER='%F{{{c["user"]}}}%n%f'
    PR_USER_OP='%F{{{c["user"]}}}%#%f'
    PR_PROMPT='%F{{{c["arrow"]}}}➤%f '
  else
    PR_USER='%F{{{c["root"]}}}%n%f'
    PR_USER_OP='%F{{{c["root"]}}}%#%f'
    PR_PROMPT='%F{{{c["root"]}}}➤%f '
  fi

  if [[ -n "$SSH_CLIENT" || -n "$SSH2_CLIENT" ]]; then
    PR_HOST='%F{{{c["ssh_host"]}}}%M%f'
  else
    PR_HOST='%F{{{c["local_host"]}}}%m%f'
  fi

  local return_code="%(?..%F{{{c['error']}}}%? ↵%f)"
  local user_host="${{PR_USER}}%F{{{c['at']}}}@${{PR_HOST}}"
  local current_dir="%B%F{{{c['path']}}}%~%f%b"
  local git_branch='$(git_prompt_info)'
  local venv_prompt='$(virtualenv_prompt_info)'

  PROMPT="%F{{{c['line']}}}╭─%f${{venv_prompt}}${{user_host}} ${{current_dir}} \\$(ruby_prompt_info) ${{git_branch}}
%F{{{c['line']}}}╰─%f$PR_PROMPT "
  RPROMPT="${{return_code}}"

  ZSH_THEME_GIT_PROMPT_PREFIX="%F{{{c['git']}}}‹"
  ZSH_THEME_GIT_PROMPT_SUFFIX='› %f'
  ZSH_THEME_RUBY_PROMPT_PREFIX="%F{{{c['ruby']}}}‹"
  ZSH_THEME_RUBY_PROMPT_SUFFIX='›%f'
  ZSH_THEME_VIRTUALENV_PREFIX="%F{{{c['venv']}}}("
  ZSH_THEME_VIRTUALENV_SUFFIX=')%f '
}}
'''


