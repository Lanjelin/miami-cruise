"""Miami Cruise configurable prompt for Oh My Zsh."""
from pathlib import Path

from palette import contrast


def render(p, variant):
    roles = {
        "user": "success", "root": "danger", "local_host": "success",
        "ssh_host": "danger", "at": "info", "path": "info", "short_path": "muted",
        "git": "warning", "ahead": "success", "behind": "danger",
        "staged": "success", "changed": "warning", "untracked": "info",
        "conflict": "danger", "ruby": "danger", "venv": "danger",
        "error": "danger", "line": "muted", "arrow": "accent",
        "duration": "warning", "jobs": "info", "mode": "accent", "time": "muted",
    }
    for role, token in roles.items():
        if contrast(p[token], p["bg"]) < 4.5:
            raise ValueError(f"zsh: {role} on bg is below 4.5:1")
    c = {role: p[token] for role, token in roles.items()}
    licence = (Path(__file__).parent / "zsh-LICENSE.txt").read_text()
    notice = "\n".join("# " + line if line else "#" for line in licence.splitlines())
    features = (Path(__file__).parent / "zsh-features.zsh").read_text()
    for role, colour in c.items():
        features = features.replace(f"@{role}@", colour)
    return f'''# Miami Cruise {variant} for Oh My Zsh. Generated by build.py.
# Configurable prompt with compact Git status and adaptive paths.
# Before loading: MIAMI_CRUISE_SINGLE_LINE=1 and/or MIAMI_CRUISE_TRANSIENT_PROMPT=1.
# Both default to 0. Transient mode also accepts same-dir; optional timestamps stay rightmost.
{notice}
setopt prompt_subst

# One Git status call per refresh, normally in a background worker.
# Counts staged, unstaged, untracked and conflicted files.
function miami_cruise_git_status() {{
  local git_output line branch='' oid='' ahead=0 behind=0 staged=0 changed=0 untracked=0 conflicts=0 xy
  git_output=$(GIT_OPTIONAL_LOCKS=0 command git status --porcelain=v2 --branch --untracked-files=normal 2>/dev/null) || return
  for line in "${{(@f)git_output}}"; do
    case "$line" in
      '# branch.head '*) branch=${{line#\\# branch.head }} ;;
      '# branch.oid '*) oid=${{line#\\# branch.oid }} ;;
      '# branch.ab '*)
        local -a counts
        counts=("${{(s: :)line}}")
        ahead=${{counts[3]#+}}
        behind=${{counts[4]#-}}
        ;;
      '1 '*|'2 '*)
        xy=${{line[3,4]}}
        [[ $xy[1] != '.' ]] && (( staged++ ))
        [[ $xy[2] != '.' ]] && (( changed++ ))
        ;;
      'u '*) (( conflicts++ )) ;;
      '? '*) (( untracked++ )) ;;
    esac
  done
  [[ -n $branch ]] || return
  [[ $branch == '(detached)' ]] && branch=${{oid[1,7]}}
  print -nr -- "%F{{{c['git']}}}${{_miami_cruise_symbols[branch]}}${{branch//\\%/%%}}"
  (( ahead > 0 )) && print -nr -- " %F{{{c['ahead']}}}${{_miami_cruise_symbols[ahead]}}${{ahead}}"
  (( behind > 0 )) && print -nr -- " %F{{{c['behind']}}}${{_miami_cruise_symbols[behind]}}${{behind}}"
  (( staged > 0 )) && print -nr -- " %F{{{c['staged']}}}+${{staged}}"
  (( changed > 0 )) && print -nr -- " %F{{{c['changed']}}}!${{changed}}"
  (( untracked > 0 )) && print -nr -- " %F{{{c['untracked']}}}?${{untracked}}"
  (( conflicts > 0 )) && print -nr -- " %F{{{c['conflict']}}}${{_miami_cruise_symbols[conflict]}}${{conflicts}}"
  print -nr -- '%f'
  miami_cruise_git_state
}}

# Keep short paths whole; when a path exceeds 80 columns (or a narrow terminal), abbreviate intermediate components
# to their shortest unique sibling prefixes. Keep the last and project roots whole.
function miami_cruise_dir() {{
  local display suffix parent full part marker other sibling prefix shown
  local -a parts
  local budget=80 shorten=0 i n unique anchor
  if [[ $PWD == $HOME ]]; then
    print -nr -- '%B%F{{{c['path']}}}~%f%b'
    return
  elif [[ $PWD == $HOME/* ]]; then
    display="~${{PWD#$HOME}}"
    suffix=${{PWD#$HOME/}}
    parent=$HOME
    print -nr -- '%B%F{{{c['path']}}}~%f%b'
  else
    display=$PWD
    suffix=${{PWD#/}}
    parent=/
    print -nr -- '%B%F{{{c['path']}}}/%f%b'
  fi
  parts=("${{(@s:/:)suffix}}")
  if (( COLUMNS > 0 && COLUMNS - 30 < budget )); then
    budget=$(( COLUMNS - 30 ))
  fi
  (( budget < 25 )) && budget=25
  (( ${{#display}} > budget )) && shorten=1
  for (( i=1; i<=${{#parts}}; i++ )); do
    part=$parts[i]
    full="${{parent%/}}/$part"
    shown=$part
    anchor=0
    [[ $parent == / && $i == 1 ]] && anchor=1
    if (( shorten && ! anchor && i < ${{#parts}} )); then
      for marker in .bzr .citc .git .hg .node-version .python-version .go-version .ruby-version .lua-version .java-version .perl-version .php-version .tool-versions .mise.toml .shorten_folder_marker .svn .terraform CVS Cargo.toml composer.json go.mod package.json stack.yaml; do
        [[ -e "$full/$marker" ]] && {{ anchor=1; break; }}
      done
      if (( ! anchor )); then
        for (( n=1; n<${{#part}}; n++ )); do
          prefix=$part[1,n]
          unique=1
          for other in "$parent"/*(ND/); do
            [[ $other == $full ]] && continue
            sibling=${{other:t}}
            if [[ $sibling[1,n] == $prefix ]]; then
              unique=0
              break
            fi
          done
          (( unique )) && break
        done
        shown=$part[1,n]
      fi
    fi
    if [[ $parent == / && $i == 1 ]]; then
      print -nr -- "%B%F{{{c['path']}}}${{shown//\\%/%%}}%f%b"
    elif (( shorten && ! anchor && i < ${{#parts}} )); then
      print -nr -- "/%F{{{c['short_path']}}}${{shown//\\%/%%}}%f"
    else
      print -nr -- "/%B%F{{{c['path']}}}${{shown//\\%/%%}}%f%b"
    fi
    parent=$full
  done
}}

{features}
() {{
  local PR_USER PR_USER_OP PR_PROMPT PR_HOST

  if [[ $UID -ne 0 ]]; then
    PR_USER='%F{{{c["user"]}}}%n%f'
    PR_USER_OP='%F{{{c["user"]}}}%#%f'
    PR_PROMPT='%F{{{c["arrow"]}}}${{_miami_cruise_arrow}}%f '
  else
    PR_USER='%F{{{c["root"]}}}%n%f'
    PR_USER_OP='%F{{{c["root"]}}}%#%f'
    PR_PROMPT='%F{{{c["root"]}}}${{_miami_cruise_arrow}}%f '
  fi

  if [[ -n "$SSH_CONNECTION" || -n "$SSH_CLIENT" || -n "$SSH2_CLIENT" || -n "$SSH_TTY" ]]; then
    PR_HOST='%F{{{c["ssh_host"]}}}%M%f'
  else
    PR_HOST='%F{{{c["local_host"]}}}%m%f'
  fi

  typeset -g _miami_cruise_user_host="${{PR_USER}}%F{{{c['at']}}}@${{PR_HOST}}"
  local user_host='$(miami_cruise_context)'
  local current_dir='${{_miami_cruise_read_only}}$(miami_cruise_dir)'
  local git_branch='$(miami_cruise_git_prompt)'

  if [[ ${{MIAMI_CRUISE_SINGLE_LINE:-0}} == 1 ]]; then
    PROMPT="${{user_host}}${{current_dir}}\\$(miami_cruise_inline_segments) $PR_PROMPT "
  else
    PROMPT="%F{{{c['line']}}}${{_miami_cruise_symbols[first]}}%f${{user_host}}${{current_dir}} \\$(miami_cruise_ruby) ${{git_branch}}
%F{{{c['line']}}}${{_miami_cruise_symbols[last]}}%f$PR_PROMPT "
  fi
  typeset -g _miami_cruise_transient_prompt="$PR_PROMPT "
  RPROMPT='${{_miami_cruise_right_prompt}}'

  ZSH_THEME_RUBY_PROMPT_PREFIX="%F{{{c['ruby']}}}${{_miami_cruise_symbols[ruby_open]}}"
  ZSH_THEME_RUBY_PROMPT_SUFFIX="${{_miami_cruise_symbols[ruby_close]}}%f"
  ZSH_THEME_VIRTUALENV_PREFIX="%F{{{c['venv']}}}("
  ZSH_THEME_VIRTUALENV_SUFFIX=')%f '
}}

# Use Zsh's hook dispatcher to preserve existing widgets and avoid duplicates.
# Temporary assignments leave the full prompt intact for the next edit.
function miami_cruise_line_finish() {{
  [[ -n $BUFFER ]] || return 0
  local transient=${{MIAMI_CRUISE_TRANSIENT_PROMPT:-0}} compact=0
  if [[ $transient == 1 ||
        ( $transient == same-dir && $_miami_cruise_last_submitted_pwd == $PWD ) ]]; then
    compact=1
  fi
  miami_cruise_timestamp_update
  miami_cruise_right_prompt_update
  if (( compact )); then
    PROMPT=$_miami_cruise_transient_prompt RPROMPT=$_miami_cruise_timestamp zle .reset-prompt
    zle -R
  elif [[ ${{MIAMI_CRUISE_SHOW_TIMESTAMP:-0}} == 1 ]]; then
    zle .reset-prompt
    zle -R
  fi
}}
if [[ -o interactive ]]; then
  autoload -Uz add-zle-hook-widget
  add-zle-hook-widget line-finish miami_cruise_line_finish
fi
'''


