def export(pals, dist):
    out = dist / "zsh"
    out.mkdir(parents=True, exist_ok=True)
    for variant, (p, _) in pals.items():
        (out / f"miami-cruise-{variant}.zsh-theme").write_text(render(p, variant))
    (out / "LICENSE-oh-my-zsh.txt").write_text((Path(__file__).parent / "zsh-LICENSE.txt").read_text())
