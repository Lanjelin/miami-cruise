def render(p, variant):
    for fg, bg in (("text", "panel"), ("text", "hover"), ("on-accent", "accent"),
                   ("text", "bg"), ("muted", "bg"), ("muted", "panel"),
                   ("muted", "hover"), ("info", "bg"), ("warning", "bg"),
                   ("bg", "success"), ("bg", "danger"), ("bg", "info"), ("bg", "warning")):
        if contrast(p[fg], p[bg]) < 4.5:
            raise ValueError(f"Yazi {variant}: {fg} on {bg} is below 4.5:1")

    def style(fg=None, bg=None, bold=False):
        parts = []
        if fg:
            parts.append(f'fg = "{p[fg]}"')
        if bg:
            parts.append(f'bg = "{p[bg]}"')
        if bold:
            parts.append("bold = true")
        return "{ " + ", ".join(parts) + " }"

    sections = {
        "mgr": {
            "cwd": style("accent", bold=True),
            "find_keyword": style("on-accent", "accent", True),
            "find_position": style("info", bold=True),
            "symlink_target": style("muted"),
            "marker_copied": style("success", "success"),
            "marker_cut": style("danger", "danger"),
            "marker_marked": style("info", "info"),
            "marker_selected": style("accent", "accent"),
            "count_copied": style("bg", "success", True),
            "count_cut": style("bg", "danger", True),
            "count_selected": style("on-accent", "accent", True),
            "border_style": style("border"),
        },
        "indicator": {
            "parent": style("muted", "hover"),
            "current": style("on-accent", "accent", True),
            "preview": style("info"),
        },
        "tabs": {
            "active": style("on-accent", "accent", True),
            "inactive": style("muted", "panel"),
        },
        "mode": {
            "normal_main": style("on-accent", "accent", True),
            "normal_alt": style("text", "panel"),
            "select_main": style("bg", "info", True),
            "select_alt": style("info"),
            "unset_main": style("bg", "warning", True),
            "unset_alt": style("warning"),
        },
        "status": {
            "overall": style("text"),
            "perm_sep": style("muted"),
            "perm_type": style("info"),
            "perm_read": style("success"),
            "perm_write": style("warning"),
            "perm_exec": style("accent"),
            "progress_label": style("text", bold=True),
            "progress_normal": style("on-accent", "accent"),
            "progress_error": style("bg", "danger"),
        },
        "which": {"border": style("accent"), "mask": style("muted"),
                  "cand": style("accent"), "rest": style("muted"),
                  "desc": style("info"), "separator_style": style("border")},
        "confirm": {"border": style("accent"), "title": style("accent", bold=True),
                    "body": style("text"), "list": style("text"),
                    "btn_yes": style("on-accent", "accent", True),
                    "btn_no": style("text", "hover")},
        "spot": {"border": style("accent"), "title": style("accent", bold=True),
                 "tbl_col": style("info"), "tbl_cell": style("on-accent", "accent")},
        "notify": {"title_info": style("info"), "title_warn": style("warning"),
                   "title_error": style("danger")},
        "pick": {"border": style("accent"), "active": style("on-accent", "accent", True),
                 "inactive": style("muted")},
        "input": {"border": style("accent"), "title": style("accent", bold=True),
                  "value": style("text"), "selected": style("on-accent", "accent")},
        "cmp": {"border": style("accent"), "active": style("on-accent", "accent", True),
                "inactive": style("text")},
        "tasks": {"border": style("accent"), "title": style("accent", bold=True),
                  "hovered": style("on-accent", "accent", True)},
        "help": {"border": style("accent"), "chord": style("info"),
                 "action": style("text"), "hovered": style("on-accent", "accent", True)},
    }
    lines = ["# Miami Cruise for Yazi. Generated by build.py; edit themes/yazi.py.",
             f"# Variant: {variant}. Install as a Yazi flavor, not as theme.toml.",
             "# Only appearance is changed; terminal background and icon glyphs are untouched.", ""]
    for section, values in sections.items():
        lines.append(f"[{section}]")
        lines.extend(f"{key} = {value}" for key, value in values.items())
        lines.append("")
    lines += ["[filetype]", "rules = [",
              f'  {{ mime = "**/image/*", fg = "{p["orchid"]}" }},',
              f'  {{ mime = "**/{{audio,video}}/*", fg = "{p["info"]}" }},',
              f'  {{ mime = "**/application/{{zip,rar,7z*,tar,gzip,xz,zstd,bzip*,lzma,compress,archive,cpio,arj,xar,ms-cab*}}", fg = "{p["orange"]}" }},',
              f'  {{ mime = "**/application/{{pdf,doc,rtf}}", fg = "{p["text"]}" }},',
              f'  {{ mime = "vfs/{{absent,stale}}", fg = "{p["disabled"]}" }},',
              f'  {{ url = "*", is = "orphan", fg = "{p["danger"]}", bold = true }},',
              f'  {{ url = "*", is = "exec", fg = "{p["success"]}" }},',
              f'  {{ url = "*/", fg = "{p["info"]}" }},',
              f'  {{ url = "*", fg = "{p["text"]}" }},',
              "]", ""]
    return "\n".join(lines)


