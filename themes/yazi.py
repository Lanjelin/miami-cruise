def export(pals, dist):
    out = dist / "yazi"
    out.mkdir(parents=True, exist_ok=True)
    licence = (out.parent.parent / "LICENSE").read_bytes()
    for variant in ("dark", "light"):
        p = pals[variant][0]
        folder = out / f"miami-cruise-{variant}.yazi"
        folder.mkdir(parents=True, exist_ok=True)
        files = {"flavor.toml": render(p, variant).encode(),
                 "tmtheme.xml": render_textmate(p, variant).encode(),
                 "LICENSE": licence}
        for name, data in files.items():
            (folder / name).write_bytes(data)
        with zipfile.ZipFile(out / f"miami-cruise-{variant}.yazi.zip", "w", zipfile.ZIP_DEFLATED) as z:
            for name, data in files.items():
                info = zipfile.ZipInfo(f"{folder.name}/{name}", date_time=(2026, 1, 1, 0, 0, 0))
                info.compress_type = zipfile.ZIP_DEFLATED
                info.external_attr = 0o644 << 16
                z.writestr(info, data)
