def export(pals, dist: Path):
    out = dist / "web"
    out.mkdir(parents=True, exist_ok=True)
    css = ["/* Miami Cruise - generated by build.py. Dark is the default; light via [data-theme=\"light\"]. */"]
    for sel, name in ((":root, [data-theme=\"dark\"]", "dark"), ("[data-theme=\"light\"]", "light")):
        p = pals[name][0]
        css.append(sel + " {\n  color-scheme: %s;\n" % name + "\n".join(f"  --mc-{k}: {p[k]};" for k in TOKEN_ORDER) + "\n}")
    (out / "miami-cruise.css").write_text("\n\n".join(css) + "\n")
    (out / "glow.css").write_text(GLOW)
