"""Native tmux styles only: no status formats, geometry, bindings or plugins."""
from palette import contrast


# Scope, native option, foreground token, background token (None = untouched).
STYLES = [
    ('s', 'status-style', 'text', 'panel'),
    ('s', 'status-left-style', 'text', 'panel'),
    ('s', 'status-right-style', 'muted', 'panel'),
    ('w', 'window-status-style', 'muted', 'panel'),
    ('w', 'window-status-current-style', 'on-accent', 'accent'),
    ('w', 'window-status-activity-style', 'info', 'bg'),
    ('w', 'window-status-bell-style', 'danger', 'bg'),
    ('w', 'window-status-last-style', 'text', 'panel'),
    ('w', 'pane-border-style', 'disabled', None),
    ('w', 'pane-active-border-style', 'accent', None),
    ('s', 'message-style', 'text', 'panel'),
    ('s', 'message-command-style', 'on-accent', 'accent'),
    ('w', 'mode-style', 'on-accent', 'accent'),
    ('s', 'menu-style', 'text', 'panel'),
    ('s', 'menu-selected-style', 'on-accent', 'accent'),
    ('s', 'menu-border-style', 'accent', 'bg'),
    ('w', 'popup-style', 'text', 'bg'),
    ('w', 'popup-border-style', 'accent', 'bg'),
]


def render(p, variant):
    lines = ['# Miami Cruise for tmux 3.4+. Generated by build.py; edit themes/tmux.py.',
             f'# Variant: {variant}. Source after other theme/plugin colour settings.',
             '# Colours only. Existing formats, separators, attributes and bindings stay intact.',
             '# Inline #[fg=...,bg=...] and local session/window overrides take precedence.',
             '# Pane contents and terminal capabilities are deliberately not configured.', '']
    for scope, option, fg, bg in STYLES:
        if bg is not None and contrast(p[fg], p[bg]) < 4.5:
            raise ValueError(f'tmux: {option} text is below 4.5:1')
        style = f'fg={p[fg]}' + (f',bg={p[bg]}' if bg else '')
        # Native style merging preserves attributes, unlike replacing the style.
        flags = '-agw' if scope == 'w' else '-ag'
        lines.append(f'set-option {flags} {option} "{style}"')
    for scope, option, token in [('s', 'display-panes-colour', 'info'),
                                  ('s', 'display-panes-active-colour', 'accent'),
                                  ('w', 'clock-mode-colour', 'accent')]:
        flags = '-gw' if scope == 'w' else '-g'
        lines.append(f'set-option {flags} {option} "{p[token]}"')
    return '\n'.join(lines) + '\n'


