"""Vim exporter: one colorscheme file with both palettes.

Output: dist/vim/colors/miami-cruise.vim  (copy into ~/.vim/colors/).
Dark and light follow 'background'. GUI and truecolor terminals get exact colours;
other terminals get the nearest xterm-256 colour. Vim has no glow, so this is the flat palette.
"""
from pathlib import Path

from . import _hl

VIM = r"""" Miami Cruise for Vim. Generated by build.py from palette.py; edit the source, not this file.
" Usage: set background=dark | light, then: colorscheme miami-cruise

highlight clear
if exists('syntax_on')
  syntax reset
endif
let g:colors_name = 'miami-cruise'

" Exact colours need a truecolor terminal; otherwise the cterm* values below are used.
if has('termguicolors') && ($COLORTERM ==# 'truecolor' || $COLORTERM ==# '24bit')
  set termguicolors
endif

if &background ==# 'light'
@@LIGHT@@
else
@@DARK@@
endif
"""

_LEVELS = (0, 95, 135, 175, 215, 255)


def _xterm256():
    """Colours 16-255 only: 0-15 are whatever the user's terminal theme says."""
    table = {}
    for i in range(216):
        table[16 + i] = (_LEVELS[i // 36], _LEVELS[(i // 6) % 6], _LEVELS[i % 6])
    for i in range(24):
        v = 8 + 10 * i
        table[232 + i] = (v, v, v)
    return table


_XTERM = _xterm256()


def nearest256(hexv):
    r, g, b = _hl._rgb(hexv)
    return min(_XTERM, key=lambda i: (_XTERM[i][0] - r) ** 2 + (_XTERM[i][1] - g) ** 2 + (_XTERM[i][2] - b) ** 2)


def _hi(name, spec):
    if "link" in spec:
        return f"  highlight! link {name} {spec['link']}"
    attrs = [a for a in ("bold", "italic", "underline", "undercurl") if spec.get(a)]
    gui = ",".join(attrs) or "NONE"
    cterm = ",".join("underline" if a == "undercurl" else a for a in attrs) or "NONE"
    parts = [f"highlight {name}"]
    for key, gkey, ckey in (("fg", "guifg", "ctermfg"), ("bg", "guibg", "ctermbg")):
        parts.append(f"{gkey}={spec[key]}" if key in spec else f"{gkey}=NONE")
        parts.append(f"{ckey}={nearest256(spec[key])}" if key in spec else f"{ckey}=NONE")
    parts.append(f"gui={gui} cterm={cterm}")
    if "sp" in spec:
        parts.append(f"guisp={spec['sp']}")
    return "  " + " ".join(parts)


def _block(p):
    groups = _hl.core(p)
    # Vim-only groups
    groups["Terminal"] = {"fg": p["text"], "bg": p["bg"]}
    groups["StatusLineTerm"] = {"link": "StatusLine"}
    groups["StatusLineTermNC"] = {"link": "StatusLineNC"}
    lines = [_hi(n, s) for n, s in groups.items()]
    colors = ", ".join(f"'{c}'" for c in _hl.ansi(p))
    lines.append(f"  let g:terminal_ansi_colors = [{colors}]")
    return "\n".join(lines)


def export(pals, dist: Path):
    out = dist / "vim" / "colors"
    out.mkdir(parents=True, exist_ok=True)
    text = VIM.replace("@@LIGHT@@", _block(pals["light"][0])).replace("@@DARK@@", _block(pals["dark"][0]))
    (out / "miami-cruise.vim").write_text(text)
