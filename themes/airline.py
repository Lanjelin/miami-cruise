"""Native vim-airline palette; independent of the editor colorscheme."""
from .vim import nearest256


def render(pals):
    ns = 'g:airline#themes#miami_cruise#palette'
    lines = ['" Generated by Miami Cruise. Do not edit.',
             'function! airline#themes#miami_cruise#refresh() abort',
             f'  let {ns} = {{}}', "  if &background ==# 'light'"]
    for variant in ('light', 'dark'):
        if variant == 'dark':
            lines.append('  else')
        p = pals[variant][0]
        def color(fg, bg, bold=False):
            return repr([p[fg], p[bg], nearest256(p[fg]), nearest256(p[bg]), 'bold' if bold else ''])
        for mode, token in [('normal', 'accent'), ('insert', 'success'), ('visual', 'warning'), ('replace', 'danger'), ('terminal', 'info'), ('inactive', 'panel')]:
            a = color('muted' if mode == 'inactive' else 'on-accent', token, mode != 'inactive')
            b, c = color('text', 'hover'), color('text', 'panel')
            lines.append(f"    let {ns}.{mode} = airline#themes#generate_color_map({a}, {b}, {c})")
            lines.append(f"    let {ns}.{mode}_modified = {{'airline_c': {color('warning', 'panel')}}}")
            for state, token in [('warning', 'warning'), ('error', 'danger')]:
                lines.append(f"    let {ns}.{mode}.airline_{state} = {color('on-accent', token, True)}")
        lines.append(f"    let {ns}.accents = {{}}")
        lines.append(f"    let {ns}.accents.red = {color('danger', 'panel')}")
    lines += ['  endif', 'endfunction', 'call airline#themes#miami_cruise#refresh()', '']
    return '\n'.join(lines)


