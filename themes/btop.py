"""Native btop .theme files. No configuration, layout or monitoring changes."""
from palette import contrast


def roles():
    colours = dict(
        main_bg="bg", main_fg="text", title="text", hi_fg="accent",
        selected_bg="accent", selected_fg="on-accent", inactive_fg="disabled",
        graph_text="text", meter_bg="border", proc_misc="orchid",
        cpu_box="info", mem_box="success", net_box="orchid", proc_box="accent",
        div_line="border", proc_pause_bg="warning", proc_follow_bg="info",
        proc_banner_bg="orchid", proc_banner_fg="bg", followed_bg="info", followed_fg="bg",
    )
    for group, tokens in dict(
        temp=("success", "warning", "danger"),
        cpu=("info", "warning", "danger"),
        free=("success", "success", "success"),
        cached=("info", "info", "info"),
        available=("success", "success", "success"),
        used=("info", "orchid", "orange"),
        download=("info", "info", "orchid"),
        upload=("orchid", "orchid", "orange"),
        # These also colour process-list text: keep all gradient stops readable.
        process=("text", "muted", "info"),
    ).items():
        for stop, token in zip(("start", "mid", "end"), tokens):
            colours[f"{group}_{stop}"] = token
    return colours


def render(p, variant):
    colours = {role: p[token] for role, token in roles().items()}
    for fg, bg in (("main_fg", "main_bg"), ("selected_fg", "selected_bg"),
                   ("proc_banner_fg", "proc_pause_bg"), ("proc_banner_fg", "proc_follow_bg"),
                   ("proc_banner_fg", "proc_banner_bg"), ("followed_fg", "followed_bg")):
        if contrast(colours[fg], colours[bg]) < 4.5:
            raise ValueError(f"btop: {fg} on {bg} is below 4.5:1")
    lines = ["# Miami Cruise for btop. Generated by build.py; edit themes/btop.py.",
             f"# Variant: {variant}. Select this .theme file in btop's Options > Color theme.",
             "# Full palette requires truecolor = true and theme_background = true.", ""]
    lines.extend(f'theme[{key}]="{value}"' for key, value in colours.items())
    return "\n".join(lines) + "\n"


