"""Delta feature definitions plus self-contained copies of its syntax themes."""
from ._textmate import export_themes, install_steps
from palette import contrast


def render(pals):
    lines = ["# Miami Cruise for delta. Generated by build.py; edit themes/delta.py.",
             "# Include this file in your Git config; select ONE named feature.", ""]
    for variant, (p, _) in pals.items():
        # Syntax tokens meet the contrast target on bg, not necessarily row/hover.
        # Keep those safe surfaces and distinguish inline edits with bold/underline.
        emphasis_bg = p["panel"] if variant == "dark" else p["bg"]
        for token in ("text", "disabled", "muted", "accent", "info", "warning", "orange", "orchid", "success", "danger"):
            for background in (p["bg"], emphasis_bg):
                if contrast(p[token], background) < 4.5:
                    raise ValueError(f"delta {variant}: {token} on {background} is below 4.5:1")
        styles = {
            variant: "true", "syntax-theme": f"miami-cruise-{variant}",
            "zero-style": 'syntax',
            "minus-style": f'"{p["danger"]}"',
            "minus-emph-style": f'"{p["danger"]}" "{emphasis_bg}" bold ul',
            "plus-style": 'syntax',
            "plus-emph-style": f'"{p["success"]}" "{emphasis_bg}" bold ul',
            "minus-non-emph-style": "minus-style", "plus-non-emph-style": "plus-style",
            "minus-empty-line-marker-style": f'"{p["danger"]}"',
            "plus-empty-line-marker-style": f'"{p["success"]}"',
            "file-style": f'"{p["accent"]}" bold',
            "file-decoration-style": f'"{p["border"]}" ul',
            "hunk-header-style": f'file line-number "{p["info"]}"',
            "hunk-header-file-style": f'"{p["info"]}"',
            "hunk-header-line-number-style": f'"{p["warning"]}"',
            "hunk-header-decoration-style": f'"{p["border"]}" box',
            "line-numbers-left-style": f'"{p["disabled"]}"',
            "line-numbers-right-style": f'"{p["disabled"]}"',
            "line-numbers-minus-style": f'"{p["danger"]}"',
            "line-numbers-plus-style": f'"{p["success"]}"',
            "line-numbers-zero-style": f'"{p["disabled"]}"',
            "commit-style": f'"{p["orchid"]}" bold',
            "commit-decoration-style": f'"{p["border"]}" box',
            "whitespace-error-style": f'"{p["bg"]}" "{p["danger"]}"',
            "keep-plus-minus-markers": "true",
        }
        lines.append(f'[delta "miami-cruise-{variant}"]')
        # Git config consumes quotes: escape them to preserve delta's hex-style syntax.
        for key, value in styles.items():
            lines.append(f'    {key} = "' + value.replace('"', '\\"') + '"')
        lines.append("")
    return "\n".join(lines)


