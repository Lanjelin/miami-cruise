#!/usr/bin/env python3
"""Regenerate docs/SPEC.md from the palette so its tables cannot drift from the source.
Run after build.py:  python3 -I docs/gen_spec.py"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
import palette as p  # noqa: E402

T = json.load(open(ROOT / "dist/tokens/tokens.json"))
C = json.load(open(ROOT / "dist/tokens/contrast.json"))

rows = []
for k in p.TOKEN_ORDER:
    cd, cl = C["dark"].get(k), C["light"].get(k)
    fmt = lambda v: "%.1f" % v if v else "-"
    rows.append(f"| `{k}` | {p.TOKEN_DOC[k]} | `{T['dark'][k]}` | {fmt(cd)} | `{T['light'][k]}` | {fmt(cl)} |")


def source(name):
    out = []
    for group in ("neutrals", "text", "accents"):
        for k, v in p.PALETTES[name][group].items():
            out.append(f"| `{k}` | {v[0]} | {v[1]} | {v[2]} | " + (f"{v[3]}:1 |" if len(v) > 3 else "- |"))
    return "\n".join(out)


md = f"""# Miami Cruise specification

Version {p.VERSION}. This file is generated by `docs/gen_spec.py` from `palette.py`; edit the source, not this file.

## Principles

1. **One hero, calm supporting colours.** Magenta (OKLCH hue {p.HERO_HUE}) is the only loud colour. It marks the primary action, selection, focus and links. Status colours (success, warning, danger, info, orange, orchid) share lightness and chroma ranges, so none competes with the hero.
2. **Meaning never depends on glow.** Selection is a tinted fill plus a solid 3px stripe, focus is a solid outline, and the primary button is a solid fill. The glow layer only decorates these.
3. **Contrast by construction.** The build raises or lowers each colour's lightness until it meets its minimum contrast against `bg`, and fails if it can't.

## Tokens

Contrast is measured against `bg` (`on-accent` against `accent`).

| Token | Use | Dark | CR | Light | CR |
|---|---|---|---|---|---|
{chr(10).join(rows)}

## OKLCH source

`L` is lightness, `C` chroma and `h` hue. The lightness shown is the starting value; the build adjusts it until the minimum contrast is met.

### Dark

| Token | L | C | h | Min contrast |
|---|---|---|---|---|
{source('dark')}

### Light

| Token | L | C | h | Min contrast |
|---|---|---|---|---|
{source('light')}

Rules of thumb for adding a colour: keep status accents near L 0.72-0.86 and C 0.10-0.17 on dark, and near L 0.58-0.62 on light; keep hues at least 30 degrees from the hero; never exceed the hero's chroma.

## Glow layer (optional)

`dist/web/glow.css`, with the custom properties `--mc-glow-hero`, `--mc-glow-focus`, `--mc-glow-text`, `--mc-select-bg` and `--mc-vignette`.

- Every glow sits on a solid state that already works without it.
- It lives in its own file or block, so a port can take it or leave it.
- It uses `@supports (color: color-mix(...))`, so unsupported environments ignore it with no fallback needed.
- It is not used where shadows don't exist (terminals, syntax colours, native UIs). There the theme is just the flat palette.
"""
(ROOT / "docs/SPEC.md").write_text(md)
